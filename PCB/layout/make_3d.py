#!/usr/bin/env python3
"""Low-fidelity VRML models for pa40 footprints that have no 3D model. Units: footprint mm (x right, y down, z up)."""
import math, os
OUT = os.path.join(os.path.dirname(__file__), '..', 'pa40.3dshapes')
S = 1 / 2.54
class Model:
    def __init__(s): s.shapes = []
    def mesh(s, verts, faces, rgb, shin=0.3):
        s.shapes.append((verts, faces, rgb, shin))
    @staticmethod
    def inward(v, f):
        # save() flips Y, which mirrors the winding: a face that points INWARD here ends up outward in the VRML,
        # the side KiCad's raytracer lights. Orient each face of a convex part toward the part centre.
        c = [sum(p[i] for p in v) / len(v) for i in range(3)]; out = []
        for fc in f:
            a, b2, d = v[fc[0]], v[fc[1]], v[fc[2]]
            e1 = [b2[i] - a[i] for i in range(3)]; e2 = [d[i] - a[i] for i in range(3)]
            n = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]]
            fcen = [sum(v[k][i] for k in fc) / len(fc) for i in range(3)]
            out.append(tuple(reversed(fc)) if sum(n[i] * (fcen[i] - c[i]) for i in range(3)) > 0 else fc)
        return out
    def box(s, x0, x1, y0, y1, z0, z1, rgb, shin=0.3):
        v = [(x, y, z) for z in (z0, z1) for y in (y0, y1) for x in (x0, x1)]
        f = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
        s.mesh(v, s.inward(v, f), rgb, shin)
    def cyl(s, p0, p1, r, rgb, n=24, shin=0.4):
        ax = [p1[i] - p0[i] for i in range(3)]; L = math.sqrt(sum(a * a for a in ax)); ax = [a / L for a in ax]
        t = [1, 0, 0] if abs(ax[0]) < 0.9 else [0, 1, 0]
        u = [ax[1] * t[2] - ax[2] * t[1], ax[2] * t[0] - ax[0] * t[2], ax[0] * t[1] - ax[1] * t[0]]
        un = math.sqrt(sum(a * a for a in u)); u = [a / un for a in u]
        w = [ax[1] * u[2] - ax[2] * u[1], ax[2] * u[0] - ax[0] * u[2], ax[0] * u[1] - ax[1] * u[0]]
        v = []
        for p in (p0, p1):
            for k in range(n):
                a = 2 * math.pi * k / n
                v.append(tuple(p[i] + r * (math.cos(a) * u[i] + math.sin(a) * w[i]) for i in range(3)))
        v += [tuple(p0), tuple(p1)]
        f = [(k, (k + 1) % n, n + (k + 1) % n, n + k) for k in range(n)]
        f += [(2 * n, (k + 1) % n, k) for k in range(n)] + [(2 * n + 1, n + k, n + (k + 1) % n) for k in range(n)]
        s.mesh(v, s.inward(v, f), rgb, shin)
    def sweep(s, path, r, rgb, n=10, closed=True, shin=0.5):
        m = len(path); v = []
        for i in range(m):
            p = path[i]; q = path[(i + 1) % m] if (closed or i < m - 1) else path[i]; o = path[i - 1] if (closed or i > 0) else path[i]
            tg = [q[k] - o[k] for k in range(3)]; tl = math.sqrt(sum(a * a for a in tg)) or 1; tg = [a / tl for a in tg]
            ref = [0, 0, 1] if abs(tg[2]) < 0.9 else [1, 0, 0]
            u = [tg[1] * ref[2] - tg[2] * ref[1], tg[2] * ref[0] - tg[0] * ref[2], tg[0] * ref[1] - tg[1] * ref[0]]
            ul = math.sqrt(sum(a * a for a in u)); u = [a / ul for a in u]
            w = [tg[1] * u[2] - tg[2] * u[1], tg[2] * u[0] - tg[0] * u[2], tg[0] * u[1] - tg[1] * u[0]]
            for k in range(n):
                a = 2 * math.pi * k / n
                v.append(tuple(p[j] + r * (math.cos(a) * u[j] + math.sin(a) * w[j]) for j in range(3)))
        f = []
        for i in range(m if closed else m - 1):
            i2 = (i + 1) % m
            for k in range(n):
                f.append((i2 * n + k, i2 * n + (k + 1) % n, i * n + (k + 1) % n, i * n + k))  # outward normals (raytracer lights front faces)
        s.mesh(v, f, rgb, shin)
    def save(s, name):
        os.makedirs(OUT, exist_ok=True)
        with open(os.path.join(OUT, name + '.wrl'), 'w') as fh:
            fh.write('#VRML V2.0 utf8\n# low-fidelity model generated by layout/make_3d.py (pa40-classe)\n')
            for verts, faces, rgb, shin in s.shapes:
                fh.write('Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f specularColor 0.3 0.3 0.3 shininess %.2f } }\n' % (*rgb, shin))
                fh.write(' geometry IndexedFaceSet { solid FALSE creaseAngle 0.6 coord Coordinate { point [\n')
                fh.write(',\n'.join('%.4f %.4f %.4f' % (x * S, -y * S, z * S) for x, y, z in verts))
                fh.write('] } coordIndex [\n')
                fh.write(',\n'.join(' '.join(str(i) for i in fc) + ' -1' for fc in faces))
                fh.write('] } }\n')

def torus_pts(R, a, b, zc, phi, t):
    rr = R + a * math.cos(t)
    return (rr * math.cos(phi), rr * math.sin(phi), zc + b * math.sin(t))

def toroid(name, R, a, b, core_rgb, turns, pads, wire_r):
    m = Model(); zc = b + 0.2; nphi, nt = 72, 16
    v = [torus_pts(R, a, b, zc, 2 * math.pi * i / nphi, 2 * math.pi * j / nt) for i in range(nphi) for j in range(nt)]
    f = [(i * nt + j, i * nt + (j + 1) % nt, ((i + 1) % nphi) * nt + (j + 1) % nt, ((i + 1) % nphi) * nt + j) for i in range(nphi) for j in range(nt)]
    m.mesh(v, f, core_rgb, 0.2)
    # winding: turns spread over 300 deg, gap centred on +Y (leads side). phi measured in footprint x/y.
    copper = (0.72, 0.42, 0.20)
    start = math.radians(90 + 30); span = math.radians(300)
    for k in range(turns):
        phi = start + span * (k + 0.5) / turns
        ring = [torus_pts(R, a + wire_r * 1.2, b + wire_r * 1.2, zc, phi, 2 * math.pi * j / 20) for j in range(20)]
        m.sweep(ring, wire_r, copper, n=8)
    # leads: from the first/last turn at the outer rim down to the pads
    for (px, py), phi in zip(pads, (start + span * 0.5 / turns, start + span * (turns - 0.5) / turns)):
        top = torus_pts(R, a + wire_r, b, zc, phi, 0)
        m.sweep([(top[0], top[1], zc), (px, py, zc * 0.6), (px, py, -1.6)], wire_r, copper, n=8, closed=False)
    m.save(name)


def render_board(out, side='top', width=2000, height=1300, quality='high', rotate=None, zoom=1,
                 pan=None, perspective=False, floor=False, background='opaque'):
    """3D render with the board stackup colours (blue mask, white silk, ENIG). Always pass
    --use-board-stackup-colors; without it KiCad's default green mask is used."""
    import subprocess
    cmd = ['kicad-cli', 'pcb', 'render', '--side', side, '--quality', quality,
           '--use-board-stackup-colors', '--background', background,
           '-w', str(width), '-h', str(height), '--zoom', str(zoom), '-o', out]
    if rotate: cmd += ['--rotate', rotate]
    if pan: cmd += ['--pan', pan]
    if floor: cmd.append('--floor')
    if perspective: cmd.append('--perspective')
    cmd.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pa40-classe.kicad_pcb'))
    subprocess.run(cmd, check=True)
    print('wrote', out)


